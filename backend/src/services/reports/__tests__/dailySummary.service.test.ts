/**
 * Daily summary generation keeps a KAM's numbers inside their client set.
 */

import { describe, it, expect, beforeEach, jest } from '@jest/globals';

const mockFetchTable = jest.fn<(table: string, ...rest: unknown[]) => Promise<unknown[]>>();
const mockPostDailySummary = jest.fn<(data: Record<string, unknown>) => Promise<{ success: boolean }>>();

jest.mock('../../airtable/n8nClient.js', () => ({
  n8nClient: {
    fetchTable: (table: string, ...rest: unknown[]) => mockFetchTable(table, ...rest),
    postDailySummary: (data: Record<string, unknown>) => mockPostDailySummary(data),
  },
}));

import { dailySummaryService } from '../dailySummary.service.js';

const applications = [
  {
    id: 'app1',
    'File ID': 'FILE-1',
    Client: 'recMine',
    Status: 'disbursed',
    'Creation Date': '2026-11-01',
    'Approved Loan Amount': '1000',
  },
  {
    id: 'app2',
    'File ID': 'FILE-2',
    Client: 'recOther',
    Status: 'disbursed',
    'Creation Date': '2026-11-01',
    'Approved Loan Amount': '5000',
  },
];

const activities = [
  {
    Timestamp: '2026-11-01T01:00:00.000Z',
    'Action Type': 'edit',
    'Performed By': 'Ada (kam)',
    'Description/Details': 'updated recMine',
    'Target Entity': '',
  },
  {
    Timestamp: '2026-11-01T02:00:00.000Z',
    'Action Type': 'edit',
    'Performed By': 'Ada (kam)',
    'Description/Details': 'updated recOther',
    'Target Entity': '',
  },
];

const audits = [
  { Timestamp: '2026-11-01T03:00:00.000Z', File: 'FILE-1', 'Action/Event Type': 'status_change', Resolved: 'False' },
  { Timestamp: '2026-11-01T04:00:00.000Z', File: 'FILE-2', 'Action/Event Type': 'status_change', Resolved: 'False' },
];

const ledger = [
  { Client: 'recMine', Date: '2026-11-01', 'Payout Amount': '10' },
  { Client: 'recOther', Date: '2026-11-01', 'Payout Amount': '99' },
];

describe('generateDailySummary scope', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    mockFetchTable.mockImplementation(async (table: string) => {
      if (table === 'Loan Application') return applications;
      if (table === 'Admin Activity Log') return activities;
      if (table === 'File Auditing Log') return audits;
      if (table === 'Commission Ledger') return ledger;
      return [];
    });
    mockPostDailySummary.mockResolvedValue({ success: true });
  });

  it('counts only the KAM clients and titles the report for their portfolio', async () => {
    const result = await dailySummaryService.generateDailySummary('2026-11-01', {
      clientIds: ['recMine'],
      clientNames: ['Mine Motors'],
      heading: "Report for Ada KAM's portfolio",
    });

    expect(result.summaryContent.startsWith("Report for Ada KAM's portfolio")).toBe(true);
    expect(result.summaryContent).not.toContain('Daily Summary Report');
    expect(result.metrics.totalApplications).toBe(1);
    expect(result.metrics.totalPayouts).toBe(10);
    expect(result.metrics.totalActivities).toBe(1);
    expect(result.metrics.statusChanges).toBe(1);
    expect(result.metrics.applicationsDisbursed).toBe(1);
    expect(result.metrics.totalDisbursedAmount).toBe(1000);
  });

  it('reads every client when no client set is passed', async () => {
    const result = await dailySummaryService.generateDailySummary('2026-11-01');
    expect(result.summaryContent.startsWith('Daily Summary Report for 2026-11-01')).toBe(true);
    expect(result.metrics.totalApplications).toBe(2);
    expect(result.metrics.totalPayouts).toBe(109);
  });

  it('returns zero metrics without reading tables when the KAM has no clients', async () => {
    const result = await dailySummaryService.generateDailySummary('2026-11-01', {
      clientIds: [],
      heading: "Report for Ada KAM's portfolio",
    });
    expect(mockFetchTable).not.toHaveBeenCalled();
    expect(result.metrics.totalApplications).toBe(0);
    expect(result.metrics.totalPayouts).toBe(0);
    expect(result.metrics.totalActivities).toBe(0);
  });

  it('saves Generated By, Scope, and a scope marker in the summary', async () => {
    const report = await dailySummaryService.generateDailySummary('2026-11-01', {
      clientIds: ['recMine'],
      heading: "Report for Ada KAM's portfolio",
    });
    await dailySummaryService.saveDailySummary(report, {
      generatedBy: 'kam@test.local',
      scope: 'kam:kam@test.local',
    });
    expect(mockPostDailySummary).toHaveBeenCalledTimes(1);
    const payload = mockPostDailySummary.mock.calls[0][0];
    expect(payload['Generated By']).toBe('kam@test.local');
    expect(payload['Scope']).toBe('kam:kam@test.local');
    expect(String(payload['Summary Content']).startsWith('[[scope:kam:kam@test.local]]')).toBe(true);
  });
});
